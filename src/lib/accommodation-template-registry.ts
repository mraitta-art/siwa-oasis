// ─── 3. HIERARCHICAL DERIVATION HELPER FUNCTIONS ─────────────────────────────

/**
 * Checks whether a section or field is active for a chosen template tier.
 */
export function isTierEligible(
  targetTier: AccommodationTemplateTier,
  requiredTier: AccommodationTemplateTier
): boolean {
  return TIER_ORDER.indexOf(targetTier) >= TIER_ORDER.indexOf(requiredTier);
}

/**
 * Derives the active sections and fields for any specific tier.
 */
export function getAccommodationTemplateSpecification(tier: AccommodationTemplateTier = 'luxury_estate') {
  const activeSections = ACCOMMODATION_SECTIONS.filter((sec) =>
    isTierEligible(tier, sec.minTier)
  ).sort((a, b) => a.order - b.order);

  const activeFields = ACCOMMODATION_FIELDS.filter((fld) =>
    isTierEligible(tier, fld.minTier)
  );

  return {
    tier,
    meta: TIER_META[tier],
    sectionsCount: activeSections.length,
    fieldsCount: activeFields.length,
    sections: activeSections.map((sec) => ({
      ...sec,
      fields: activeFields.filter((f) => f.sectionId === sec.id),
    })),
  };
}

